import {
  ArrowLeftRight,
  Banknote,
  Bell,
  Boxes,
  Building2,
  CircleDot,
  CreditCard,
  Database,
  FileBarChart,
  FileText,
  Gauge,
  KeyRound,
  Landmark,
  LayoutDashboard,
  LifeBuoy,
  Megaphone,
  Network,
  Percent,
  PiggyBank,
  Receipt,
  Settings,
  ShieldCheck,
  Smartphone,
  Tv,
  UserCog,
  UserPlus,
  Users,
  Wallet,
  type LucideIcon,
} from 'lucide-react';

// Keyword → icon. Matched against the menu item's name + icon string (best effort,
// since backend icon strings come from the legacy menu definition).
const KEYWORDS: Array<[string, LucideIcon]> = [
  ['dashboard', LayoutDashboard],
  ['recharge', Smartphone],
  ['dth', Tv],
  ['report', FileBarChart],
  ['transaction', Receipt],
  ['fund', Wallet],
  ['wallet', Wallet],
  ['transfer', ArrowLeftRight],
  ['payout', Banknote],
  ['dmt', Banknote],
  ['aeps', Landmark],
  ['bank', Landmark],
  ['commission', Percent],
  ['card', CreditCard],
  ['user', Users],
  ['retailer', Users],
  ['distributor', Network],
  ['onboard', UserPlus],
  ['kyc', ShieldCheck],
  ['role', UserCog],
  ['setting', Settings],
  ['config', Settings],
  ['provider', Boxes],
  ['operator', Boxes],
  ['notification', Bell],
  ['message', Megaphone],
  ['invoice', FileText],
  ['tax', FileText],
  ['document', FileText],
  ['ledger', Database],
  ['accounting', PiggyBank],
  ['support', LifeBuoy],
  ['complaint', LifeBuoy],
  ['key', KeyRound],
  ['company', Building2],
  ['performance', Gauge],
];

export function pickIcon(name?: string, icon?: string): LucideIcon {
  const hay = `${icon ?? ''} ${name ?? ''}`.toLowerCase();
  for (const [kw, Icon] of KEYWORDS) {
    if (hay.includes(kw)) return Icon;
  }
  return CircleDot;
}

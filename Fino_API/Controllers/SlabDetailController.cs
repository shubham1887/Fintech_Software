        public SlabDetailController(ISlabDetailService service, IReportAnalyticsService analytics, IConfiguration configuration)
        {
            _service = service;
            _analytics = analytics;
            _logger = new Logger();
            string encryptionKey = configuration["Encryption:Key"] ?? string.Empty;
            string encryptionIV = configuration["Encryption:IV"] ?? string.Empty;
            _encryptDecrypt = new EncryptDecrypt(encryptionKey, encryptionIV);
        }

        /// <summary>
        /// "What does my slab pay me?" — the commission structure of the slab assigned to the
        /// caller (or, for admin / a distributor's downline, to the requested user), resolved into
        /// service + operator + amount-band rows with the caller's own tier rate spelled out.
        ///
        /// Unlike GetAll (an admin CRUD listing of every slab in the system) this is a
        /// user-facing report: it is scoped, enriched with names, and safe for downline roles.
        /// </summary>
        [HttpPost("CommissionStructure")]
        public async Task<APIResponse> CommissionStructure([FromForm] APIRequest apiRequest)
        {
            KeyDataModel? keyDataModel;
            Requests.TransactionReport.TxnReportRequest? request;
            try
            {
                keyDataModel = JsonConvert.DeserializeObject<KeyDataModel>(_encryptDecrypt.Decrypt(apiRequest.KeyData));
                request = JsonConvert.DeserializeObject<Requests.TransactionReport.TxnReportRequest>(_encryptDecrypt.Decrypt(apiRequest.Request));
            }
            catch (Exception ex)
            {
                _logger.Write(ex);
                return ResponseProcess.GetFailResponse(Messages.Common.Message.ExceptionOccured);
            }

            if (keyDataModel == null)
                return ResponseProcess.GetFailResponse(Messages.Common.Message.InvalidRequest);

            string failureMessage = keyDataModel.IsValidModalState();
            if (!failureMessage.EqualsIgnoreCase(StaticModels.StatusType.Ok))
                return ResponseProcess.GetFailResponse(failureMessage);

            var (fail, data) = await _analytics.CommissionStructure(
                request ?? new Requests.TransactionReport.TxnReportRequest(),
                keyDataModel.UserID,
                keyDataModel.UserTypeID);
            if (!string.IsNullOrEmpty(fail)) return ResponseProcess.GetFailResponse(fail);
            return ResponseProcess.GetSuccessResponse(JsonConvert.SerializeObject(data));
        }


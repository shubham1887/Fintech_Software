using FintechApp.Authorization;
using FintechApp.Helpers;
using FintechApp.Interfaces.Services;
using FintechApp.Requests;
using FintechApp.Requests.CallMeRequest;
using FintechApp.Responses;
using Microsoft.AspNetCore.Mvc;
using Newtonsoft.Json;


namespace FintechApp.Controllers
{
    [Route("api/[controller]")]
    [ApiController]
    [JwtAuthorization]
    public class CallMeRequestController : ControllerBase
    {
        private readonly ICallMeRequestService _callMeRequestService;
        private readonly EncryptDecrypt _encryptDecrypt;
        private readonly Logger _logger;

        public CallMeRequestController(ICallMeRequestService callMeRequestService, IConfiguration configuration)
        {
            _callMeRequestService = callMeRequestService;
            _logger = new Logger();

            string encryptionKey = configuration["Encryption:Key"] ?? string.Empty;
            string encryptionIV = configuration["Encryption:IV"] ?? string.Empty;
            _encryptDecrypt = new EncryptDecrypt(encryptionKey, encryptionIV);
        }

        [HttpPost("GetById")]
        public async Task<APIResponse> GetById([FromForm] APIRequest apiRequest)
        {
            KeyDataModel? keyDataModel;
            GetCallMeRequestRequest? getCallMeRequestRequest;

            try
            {
                string decryptedKeyData = _encryptDecrypt.Decrypt(apiRequest.KeyData);
                keyDataModel = JsonConvert.DeserializeObject<KeyDataModel>(decryptedKeyData);

                string decryptedRequest = _encryptDecrypt.Decrypt(apiRequest.Request);
                getCallMeRequestRequest = JsonConvert.DeserializeObject<GetCallMeRequestRequest>(decryptedRequest);
            }
            catch (Exception ex)
            {
                _logger.Write(ex);
                return ResponseProcess.GetFailResponse(Messages.Common.Message.ExceptionOccured);
            }

            if (keyDataModel == null || getCallMeRequestRequest == null)
                return ResponseProcess.GetFailResponse(Messages.Common.Message.InvalidRequest);

            string failureMessage = keyDataModel.IsValidModalState();
            if (!failureMessage.EqualsIgnoreCase(StaticModels.StatusType.Ok))
                return ResponseProcess.GetFailResponse(failureMessage);

            try
            {
                var callMeRequest = await _callMeRequestService.GetCallMeRequestById(getCallMeRequestRequest.CallMeRequestID);

                if (callMeRequest == null)
                    return ResponseProcess.GetFailResponse(Messages.CallMeRequestMessages.CallMeRequestNotFound);

                string encryptedResponse = _encryptDecrypt.Encrypt(JsonConvert.SerializeObject(callMeRequest));
                return ResponseProcess.GetSuccessResponse(encryptedResponse);
            }
            catch (Exception ex)
            {
                _logger.Write(ex);
                return ResponseProcess.GetErrorResponse(Messages.Common.Message.ExceptionOccured);
            }
        }


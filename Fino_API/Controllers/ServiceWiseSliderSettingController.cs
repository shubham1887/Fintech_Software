            try { var data = await _service.GetByID(request.ServiceWiseSliderSettingID); if (data == null) return ResponseProcess.GetFailResponse(Messages.ServiceWiseSliderSettingMessages.NotFound); return ResponseProcess.GetSuccessResponse(_encryptDecrypt.Encrypt(JsonConvert.SerializeObject(data))); }
            catch (Exception ex) { _logger.Write(ex); return ResponseProcess.GetErrorResponse(Messages.Common.Message.ExceptionOccured); }
        }


using System.ComponentModel;
using System.ComponentModel.DataAnnotations;
using System.ComponentModel.DataAnnotations.Schema;

namespace FintechApp.Entities
{
    public class ProviderMaster : BaseEntity
    {
        [Key]
        [DatabaseGenerated(DatabaseGeneratedOption.Identity)]
        public int ProviderID { get; set; }

        [Required]
        [Column(TypeName = "varchar(150)")]
        public string ProviderName { get; set; } = string.Empty;

        [Required]
        [Column(TypeName = "varchar(max)")]
        public string ProviderUrl { get; set; } = string.Empty;

        [Column(TypeName = "varchar(150)")]
        public string ProviderUniqueID { get; set; } = string.Empty;

        /// <summary>
        /// Public, opaque id for THIS provider integration. It is the only thing that separates one
        /// upstream from another on the one shared callback address we hand out:
        ///     https://&lt;our-host&gt;/api/Callback/p/{CallbackKey}
        /// Generated by us, never a credential (unlike <see cref="ProviderUniqueID"/>, which is
        /// JaiJui's auth code) — so it is safe to put in a URL and give to the provider.
        /// </summary>
        [Column(TypeName = "varchar(64)")]
        public string CallbackKey { get; set; } = string.Empty;

        [Column(TypeName = "varchar(100)")]
        public string IPAddress { get; set; } = string.Empty;

        [DefaultValue(false)]
        public bool IsDelete { get; set; }

        [DefaultValue(true)]
        public bool IsActive { get; set; }

        [DefaultValue(false)]
        public bool IsHLR { get; set; }

        [Column(TypeName = "decimal(18,5)")]
        public decimal RechargeBalance { get; set; }

        [Column(TypeName = "decimal(18,5)")]
        public decimal DMTBalance { get; set; }

        public int ResponseGroupID { get; set; }

        [DefaultValue(false)]
        public bool IsRealAPI { get; set; }

        [Column(TypeName = "varchar(200)")]
        public string LoginID { get; set; } = string.Empty;

        [Column(TypeName = "varchar(200)")]
        public string Token { get; set; } = string.Empty;

        [Column(TypeName = "varchar(10)")]
        public string SupportNumber { get; set; } = string.Empty;

        public int LowBalanceAmount { get; set; }
    }
}

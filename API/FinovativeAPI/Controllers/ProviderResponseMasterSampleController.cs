        [HttpPost]
        public APIResponse UpdateSampleResponseToProvider([FromForm] APIRequest encRequest)
        {
            KeyDataModel keyDataModel;
            List<UpdateSampleResponseRequest> mainRequest;
            string failureMessage = encRequest.IsValidModalState();
            if (!failureMessage.EqualsIgnoreCase(StatusType.Ok))
                return ResponseProcess.GetFailReason(failureMessage);

            try
            {
                keyDataModel = JsonConvert.DeserializeObject<KeyDataModel>(ed.Decrypt(encRequest.KeyData));
                mainRequest = JsonConvert.DeserializeObject<List<UpdateSampleResponseRequest>>(ed.Decrypt(encRequest.Request));
            }
            catch (Exception ex)
            {
                new Logger().Write(ex);
                return ResponseProcess.GetFailReason(Messages.InvalidUserInput);
            }
            failureMessage = keyDataModel.IsValidModalState();

            if (!failureMessage.EqualsIgnoreCase(StatusType.Ok))
                return ResponseProcess.GetFailReason(failureMessage);
            string Result = "";
            try
            {
                Result = new ProviderResponseMasterSampleBal().UpdateSampleResponseToProvider(mainRequest, out string failureMessge);
            }
            catch (Exception ex)
            {
                new Logger().Write(ex);
                return ResponseProcess.GetFailReason(Messages.ExceptionOccured,
                     keyDataModel.UserID, "UpdateSampleResponseToProvider", mainRequest.ToString());
            }

            if (!failureMessage.EqualsIgnoreCase(StatusType.Ok))
                return ResponseProcess.GetFailReason(failureMessage,
                     keyDataModel.UserID, "UpdateSampleResponseToProvider", mainRequest.ToString());

            return ResponseProcess.GetSucessReason(Result,
                 keyDataModel.UserID, "UpdateSampleResponseToProvider", mainRequest.ToString());
        }

        [HttpPost]
        public APIResponse SelectDeveloperForDropDown([FromForm] APIRequest aPIRequest)
        {
            List<DeveloperViewModel> DeveloperList;

            try
            {
                DeveloperList = new ProviderResponseMasterSampleBal().SelectDeveloperForDropDown();
            }
            catch (Exception ex)
            {
                new Logger().Write(ex);
                return ResponseProcess.GetFailReason(Messages.ExceptionOccured);
            }

            if (DeveloperList == null || DeveloperList.Count <= 0)

                return ResponseProcess.GetFailReason(ProviderMessage.ProviderNotFound);

            return ResponseProcess.GetSucessReason(JsonConvert.SerializeObject(DeveloperList));
        }


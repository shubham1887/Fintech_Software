/* ============================================================================
   Pay1 Utility (BBPS) - biller routing for the whole catalogue
   ----------------------------------------------------------------------------
   pay1_bbps_seed.sql creates the Pay1 provider row and routes ONE biller as a
   worked example. This routes the lot: every biller on Pay1's live catalogue
   (operation_type 7), paired with the operator that serves it here.

   Run it AFTER pay1_bbps_seed.sql (which creates the provider and holds the
   credentials) and AFTER 55_seed_bbps_biller_catalogue.sql (which creates the
   billers themselves). Idempotent: re-running updates product ids that moved and
   adds routes that are missing, and changes nothing else.

   What it does per biller:
     * ProviderConfigurations - the route, carrying Pay1's product_id in OpCode
     * OperatorSequences      - the switching order, WITHOUT which the gateway
                                treats the biller as "no provider authorised".
                                Pay1 goes at the BACK of whatever a biller already
                                has (max existing + 10), so a biller already live
                                on another provider keeps using it.
     * switches the biller ON - billers ship inactive precisely so that this,
                                the moment they have somebody to serve them, is
                                when they appear.

   GENERATED - re-run the generator rather than editing.
   ============================================================================ */

